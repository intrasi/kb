#!/usr/bin/env python3
"""Knowledge-base helper. Standard library only; `pdf` also needs `pdftotext` (poppler).

Usage:
  python3 scripts/kb.py check            # validate frontmatter, tags, and links; exit 1 on error
  python3 scripts/kb.py index            # rewrite INDEX.md
  python3 scripts/kb.py pdf <file.pdf>   # copy into sources/papers/ and extract <slug>.md

Safe to run twice.
"""
import re
import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIRS = {"notes": "note", "questions": "question", "decisions": "decision", "sources": "source"}
REQUIRED = {
    "note": ["title", "tags", "date", "by", "confidence"],
    "question": ["title", "tags", "date", "by", "status"],
    "decision": ["title", "tags", "date", "by", "status"],
    "source": ["title", "date"],
}
ALLOWED = {
    "confidence": {"high", "moderate", "low"},
    "status": {"open", "answered", "dropped", "active", "superseded"},
}
LINK = re.compile(r"\[\[([^\]|#]+)")


def parse(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---", 4)
    if end == -1:
        return None, text
    meta = {}
    for line in text[4:end].splitlines():
        m = re.match(r"^([a-z_]+):\s*(.*)$", line)
        if not m:
            continue
        key, val = m.group(1), m.group(2).split(" #")[0].strip()
        if val.startswith("[") and val.endswith("]"):
            val = [v.strip().strip("'\"") for v in val[1:-1].split(",") if v.strip()]
        meta[key] = val
    return meta, text[end + 4:]


def files():
    for d in DIRS:
        for p in sorted((ROOT / d).rglob("*.md")):
            yield d, p


def tags():
    out = set()
    for line in (ROOT / "TAGS.md").read_text().splitlines():
        m = re.match(r"^- ([a-z0-9-]+):", line)
        if m:
            out.add(m.group(1))
    return out


def check():
    allowed_tags, errors = tags(), []
    slugs = {p.stem for _, p in files()}
    for d, p in files():
        rel = p.relative_to(ROOT)
        meta, body = parse(p)
        if meta is None:
            errors.append(f"{rel}: missing frontmatter")
            continue
        kind = meta.get("type")
        if kind != DIRS[d]:
            errors.append(f"{rel}: type should be '{DIRS[d]}', found '{kind}'")
            continue
        for key in REQUIRED[kind]:
            if not meta.get(key):
                errors.append(f"{rel}: missing '{key}'")
        for key, ok in ALLOWED.items():
            if key in meta and meta[key] not in ok:
                errors.append(f"{rel}: {key} '{meta[key]}' not in {sorted(ok)}")
        tag_list = meta.get("tags") or []
        if isinstance(tag_list, str):
            errors.append(f"{rel}: tags must be a list like [pqc, tls]")
            tag_list = []
        for t in tag_list:
            if t not in allowed_tags:
                errors.append(f"{rel}: unknown tag '{t}' (add it to TAGS.md)")
        for link in LINK.findall(body + str(meta.get("sources", ""))):
            if link.strip() not in slugs:
                errors.append(f"{rel}: broken link [[{link}]]")
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", p.stem):
            errors.append(f"{rel}: filename must be a kebab-case slug")
    for e in errors:
        print(e)
    print(f"{len(errors)} error(s)" if errors else "ok")
    return 1 if errors else 0


def index():
    lines = [
        "# Index",
        "",
        "Generated by `scripts/kb.py index`. Do not edit by hand.",
        "",
    ]
    for d in DIRS:
        rows = []
        for dd, p in files():
            if dd != d:
                continue
            meta, _ = parse(p)
            meta = meta or {}
            t = meta.get("tags") or []
            extra = meta.get("status") or meta.get("confidence") or ""
            owner = f" ({meta['owner']})" if meta.get("owner") and extra == "open" else ""
            rel = p.relative_to(ROOT).as_posix()
            title = str(meta.get("title", p.stem)).replace("|", "/")
            rows.append(f"| [{p.stem}]({rel}) | {title} | {', '.join(t) if isinstance(t, list) else t} | {extra}{owner} |")
        lines += [f"## {d.capitalize()} ({len(rows)})", ""]
        if rows:
            lines += ["| Slug | Title | Tags | State |", "| --- | --- | --- | --- |", *rows]
        else:
            lines.append("None yet.")
        lines.append("")
    new = "\n".join(lines)
    target = ROOT / "INDEX.md"
    if not target.exists() or target.read_text() != new:
        target.write_text(new)
        print("INDEX.md updated")
    else:
        print("INDEX.md unchanged")
    return 0


def pdf(src):
    src = Path(src).expanduser().resolve()
    slug = re.sub(r"[^a-z0-9]+", "-", src.stem.lower()).strip("-")
    out_dir = ROOT / "sources" / "papers"
    out_dir.mkdir(parents=True, exist_ok=True)
    dest = out_dir / f"{slug}.pdf"
    if src != dest:
        shutil.copyfile(src, dest)
    md = out_dir / f"{slug}.md"
    if md.exists():
        print(f"{md.relative_to(ROOT)} exists; left unchanged")
        return 0
    if not shutil.which("pdftotext"):
        sys.exit("pdftotext not found: brew install poppler, or apt install poppler-utils")
    text = subprocess.run(["pdftotext", "-layout", str(dest), "-"], capture_output=True, text=True).stdout
    md.write_text(
        "---\n"
        "type: source\n"
        f"title: {src.stem}\n"
        f"date: {date.today().isoformat()}\n"
        f"file: {dest.name}\n"
        "url:\n"
        "tags: []\n"
        "---\n\n"
        "Fill in `title` and `url`. Text below is machine-extracted from the PDF.\n\n"
        + text
    )
    print(f"wrote {md.relative_to(ROOT)}; set its title and url, then write notes from it")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "check":
        sys.exit(check())
    if cmd == "index":
        sys.exit(index())
    if cmd == "pdf" and len(sys.argv) == 3:
        sys.exit(pdf(sys.argv[2]))
    sys.exit(__doc__)
